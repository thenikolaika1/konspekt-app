export function userPrompt(pageCount: number): string {
  return `Перед тобой ${pageCount} ${plural(pageCount)} одной темы в правильном порядке.\nСделай полный, но удобный конспект только по этим страницам.\nОсобенно проверь перед ответом: (1) разделы совпадают с учебником; (2) в содержательных абзацах есть смысловые **выделения**; (3) материал не выглядит пустым — определения, перечисления, сравнения и процессы вынесены в подходящие карточки; (4) карточки не дублируют текст; (5) meta.pages содержит ровно ${pageCount} элементов.\n\n${SCHEMA}\n\nВерни только JSON-объект.`;
}

export function retryPrompt(problems: string[]): string {
  return `Предыдущий ответ имеет критические проблемы:\n${problems.map((p) => "- " + p).join("\n")}\nИсправь их, используя те же фотографии. Не добавляй внешних знаний. Сохрани структуру пунктов учебника, плотный связный текст, смысловые выделения и подходящие карточки. Верни только корректный JSON по той же схеме.`;
}

function plural(n: number) {
  const m10 = n % 10, m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return "фотография страницы";
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return "фотографии страниц";
  return "фотографий страниц";
}
