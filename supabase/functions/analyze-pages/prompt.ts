export function userPrompt(pageCount: number): string {
  return `Вот ${pageCount} ${plural(pageCount)} учебника по одной теме, в правильном порядке (первая фотография — страница с index 0).
Составь конспект строго по этим страницам в утверждённом формате.
В meta.pages должно быть ровно ${pageCount} ${pageCount === 1 ? "элемент" : "элементов"} — по одному на каждую фотографию.

${SCHEMA}

Верни только JSON-объект.`;
}

/** Повторный запрос: предыдущий ответ не разобрался или нарушил формат — перечисляем конкретные проблемы. */
export function retryPrompt(problems: string[]): string {
  return `Предыдущий ответ не подходит. Проблемы:
${problems.map((p) => "- " + p).join("\n")}

Составь конспект заново по тем же фотографиям и исправь эти проблемы.
Пиши короче и своими словами, каждый факт один раз. Русские слова — только кириллицей; фрагменты, которые нельзя надёжно прочитать, не включай.
Верни ТОЛЬКО один корректный JSON-объект по схеме выше: без текста до и после, без \`\`\`, без HTML.`;
}

function plural(n: number) {
  const m10 = n % 10, m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return "фотография страницы";
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return "фотографии страниц";
  return "фотографий страниц";
}
