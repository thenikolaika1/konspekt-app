#!/usr/bin/env node
// Постоянный пароль панели владельца (v61.3) — генерация на твоём компьютере.
//
// Запуск локально (не в CI и не на сервере):  node tools/owner-panel-password.mjs
//
// Печатает пароль ТОЛЬКО на экран: никуда не отправляет, не сохраняет в файлы и не пишет в SQL.
// Дальше: приложение → Я → «Панель владельца» → «Установить пароль» → «У меня пароль из генератора».
// Пароль никому не показывай, не коммить и не вставляй в переписку; сохрани его в менеджере паролей.
// Генератор тот же, что встроен в панель: 20 символов алфавита ID (без 0/O/1/I/L), ≈99 бит, без смещения.

import { randomInt } from "node:crypto";

const ALPHABET = "ABCDEFGHJKMNPQRSTUVWXYZ23456789";
let s = "";
for (let i = 0; i < 20; i++) s += ALPHABET[randomInt(ALPHABET.length)];
console.log("\nПароль панели владельца (сохрани прямо сейчас):\n\n  " + s.replace(/(.{5})(?=.)/g, "$1-") + "\n");
